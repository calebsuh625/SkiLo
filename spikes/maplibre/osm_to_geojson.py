#!/usr/bin/env python3
"""Convert the Overpass `out geom` JSON for Heavenly into GeoJSON for MapLibre.

Usage: osm_to_geojson.py <heavenly_osm.json> <out.geojson> <out.js>

Writes two files with identical content:
  * out.geojson  - a FeatureCollection (for tooling / future native use)
  * out.js       - `window.HEAVENLY_GEOJSON = {...};` so the spike page can load it
                   with a plain <script src> from file:// (no fetch(), no CORS/file-access prefs).

Feature kinds (properties.kind): "piste" (LineString), "lift" (LineString),
"boundary" (MultiLineString from the winter_sports relation's outer ways).
aerialway=station ways (building outlines) are skipped. Stdlib only.
Source data: OpenStreetMap, ODbL 1.0.
"""
import json
import sys


def way_coords(el):
    return [[round(p["lon"], 7), round(p["lat"], 7)] for p in el.get("geometry") or []]


def main(src, out_geojson, out_js):
    with open(src) as f:
        data = json.load(f)

    feats = []
    stats = {"piste": 0, "piste_vertices": 0, "lift": 0, "station_skipped": 0,
             "boundary": 0, "other_skipped": 0, "difficulty": {}, "unique_piste_names": 0}
    names = set()

    for el in data["elements"]:
        tags = el.get("tags") or {}
        if el["type"] == "way":
            coords = way_coords(el)
            if len(coords) < 2:
                stats["other_skipped"] += 1
                continue
            if tags.get("piste:type") == "downhill":
                diff = tags.get("piste:difficulty") or "unknown"
                name = tags.get("name")
                if name:
                    names.add(name)
                feats.append({
                    "type": "Feature", "id": el["id"],
                    "geometry": {"type": "LineString", "coordinates": coords},
                    "properties": {
                        "kind": "piste", "id": el["id"],
                        "name": name or "(unnamed run)", "named": bool(name),
                        "difficulty": diff,
                        "grooming": tags.get("piste:grooming"),
                        "gladed": tags.get("gladed"),
                        "oneway": tags.get("piste:oneway"),
                    },
                })
                stats["piste"] += 1
                stats["piste_vertices"] += len(coords)
                stats["difficulty"][diff] = stats["difficulty"].get(diff, 0) + 1
            elif "aerialway" in tags:
                if tags["aerialway"] == "station":
                    stats["station_skipped"] += 1
                    continue
                feats.append({
                    "type": "Feature", "id": el["id"],
                    "geometry": {"type": "LineString", "coordinates": coords},
                    "properties": {"kind": "lift", "id": el["id"],
                                   "name": tags.get("name") or "(unnamed lift)",
                                   "aerialway": tags["aerialway"]},
                })
                stats["lift"] += 1
            else:
                stats["other_skipped"] += 1
        elif el["type"] == "relation" and tags.get("landuse") == "winter_sports":
            lines = [way_coords(m) for m in el.get("members") or []
                     if m.get("type") == "way" and m.get("geometry")]
            lines = [l for l in lines if len(l) >= 2]
            feats.append({
                "type": "Feature", "id": el["id"],
                "geometry": {"type": "MultiLineString", "coordinates": lines},
                "properties": {"kind": "boundary", "id": el["id"], "name": tags.get("name")},
            })
            stats["boundary"] += 1

    stats["unique_piste_names"] = len(names)
    fc = {"type": "FeatureCollection",
          "attribution": "(c) OpenStreetMap contributors, ODbL 1.0",
          "features": feats}
    body = json.dumps(fc, separators=(",", ":"))
    with open(out_geojson, "w") as f:
        f.write(body)
    with open(out_js, "w") as f:
        f.write("// Generated by osm_to_geojson.py from data/raw/heavenly_osm.json "
                "(OpenStreetMap, ODbL). Do not edit.\n")
        f.write("window.HEAVENLY_GEOJSON = " + body + ";\n")
    print(json.dumps(stats))


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:4])
